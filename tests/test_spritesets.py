def test_parse_rss():
	f = io.BytesIO(_sphere_testspriteset_bytes)
	
	spriteset = formats.spriteset.SphereSpriteset()
	spriteset.filePath = "test.rss"
	spriteset._parseFileData(f)
	assert spriteset.version == 3
	assert len(spriteset.directions) == 4
	assert len(spriteset.directions[0].frames) == 4
	assert len(spriteset.directions[1].frames) == 1
	assert len(spriteset.directions[2].frames) == 1
	assert len(spriteset.directions[3].frames) == 1
	for d in range(len(spriteset.directions)):
		dir = spriteset.directions[d]
		for frame in dir.frames:
			assert frame.delay == 8

	assert len(spriteset.images) == 4
	for img in spriteset.images:
		assert img.width() == spriteset.frameWidth and img.width() > 0
		assert img.height() == spriteset.frameHeight and img.height() > 0

	assert spriteset.baseX1 == 2 and spriteset.baseX2 == 11
	assert spriteset.baseY1 == 2 and spriteset.baseY2 == 20
